// Generates dashboard/src/types/contracts.ts from ../contracts/*.schema.json. Never hand-edit the output.
import { compileFromFile } from "json-schema-to-typescript"
import { readdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const dir = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "contracts")
const names = readdirSync(dir).filter((f) => f.endsWith(".schema.json") && f !== "common.schema.json")
let out = "// GENERATED by scripts/gen-types.mjs from /contracts. Do not edit; run `npm run gen:types`.\n/* eslint-disable */\n"
for (const f of names) {
	const ts = await compileFromFile(join(dir, f), { bannerComment: "", additionalProperties: false, cwd: dir, unreachableDefinitions: false })
	out += `\n${ts}`
}
writeFileSync(resolve(dirname(fileURLToPath(import.meta.url)), "..", "src", "types", "contracts.ts"), out)
console.log(`wrote ${names.length} schemas`)
